const unclearResult = "Não foi possível confirmar o resultado. Consulta os trabalhos anteriores antes de repetir o pedido.";
async function api(path, data) {
  const options = {method:data === undefined ? "GET":"POST",
    headers:{"X-Nexus-Session":session,"Content-Type":"application/json"},
    body:data === undefined ? undefined:JSON.stringify(data)};
  let response, value;
  try {
    response = await fetch(path, options);
    value = await response.json();
  } catch(error) {
    // The confirmed operation may have run even if its reply was lost/broken.
    // Consumed tickets remain consumed; do not infer denial or retry here.
    if (path === "/api/confirm-run" || path === "/api/approve") throw new Error(unclearResult);
    throw error;
  }
  if (!response.ok) throw new Error(value?.outcome === "UNKNOWN" ? unclearResult : value?.error || "Não foi possível concluir.");
  return value;
}
function userMessage(message) {
  const text=String(message || "");
  return /\b(?:OpenNotebook|Open Notebook|LanguageTool|LibreOffice|Writer|Sandy|ACE-Step|Kernel|Host|Canonical|Creative|LPAC|DACL|FTS5|MCP|SHA-256)\b/iu.test(text)
    ? "Não foi possível concluir este trabalho. O pedido foi conservado; tenta novamente mais tarde."
    : text;
}
function notice(message) { el("notice").textContent = userMessage(message); el("notice").hidden = !message; }
function resultText(content,process) {
  // Presentation only. Raw results, evidence, downloads and approval bindings
  // stay unchanged. Remove only metadata generated by the existing adapters.
  let text=String(content || "");
  if(process==="book" || process==="convert_pdf")
    text=text.replace(/\n\nPDF SHA-256: [0-9a-f]{64}$/u,"");
  if(process==="verify")
    text=text.replace(/\n\nMétodo 1: (?:PASS|FAIL|UNKNOWN)\n(?:[0-9a-f]{64}|Sem resultado)\n\nMétodo 2: (?:PASS|FAIL|UNKNOWN)\n(?:[0-9a-f]{64}|Sem resultado)$/u,"");
  if(process==="music")
    text=text.replace(/\n\n## Destino\nACE-Step local\. A geração de áudio físico é validada no gate pós-instalação\.$/u,
      "\n\n## Produção\nEste resultado é um plano. A produção e a validação do áudio continuam pendentes.");
  if(process==="web")
    text=text.replace(/A rota está autorizada, mas não inventa fontes: resultados só entram após um fornecedor web real devolver fontes verificáveis e o Kernel as comparar\.$/u,
      "A pesquisa ainda não foi executada. As fontes e os factos precisam de verificação.");
  return text;
}
